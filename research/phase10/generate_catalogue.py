#!/usr/bin/env python3
"""Render the bounded finite-certificate candidates as ordinary Lean data.

The generator is not trusted by the proofs: Lean separately checks every
Valid predicate by ordinary kernel reduction. No seed intervals are searched.
"""

import argparse
import itertools
from pathlib import Path
import sys

sys.dont_write_bytecode = True
from search_unequal import analyze, closed_language, column_certificate, prefix
from verify_unequal import affine, orbit_prefix


ROOT = Path(__file__).resolve().parents[2]
NAMES = {3: "Three", 4: "Four", 5: "Five", 6: "Six"}
COUNTS = {3: 6, 4: 10, 5: 58, 6: 148}


def lean_list(xs):
    return "[" + ",".join(xs) + "]"


def bits(xs):
    return lean_list("true" if b else "false" for b in xs)


def render_entry(one, zero, h, cap, language, columns):
    return (f"  {{ length := {len(one)}, one := {bits(one)}, zero := {bits(zero)},\n"
            f"    blocks := {h}, cap := {cap}, distinguish := {columns['distinguish']},\n"
            f"    separate := {lean_list(map(str, columns['separate']))},\n"
            f"    language := {lean_list(bits(xs) for xs in language)} }}")


def verify_signed_prefixes(one, zero):
    word = prefix(one, zero, 81)
    odd, offset = affine(word)
    modulus = 2**81
    inverse = pow(3**odd, -1, modulus)
    positive = (-offset * inverse) % modulus
    negative = (-5 * offset * inverse) % modulus - modulus
    for p, q in ((positive, 1), (negative, 5), (3 * negative, 15)):
        parity, states = orbit_prefix(p, q, 81)
        assert parity == word
        assert modulus * states[-1] == 3**odd * p + offset * q


def build_modules():
    modules = {}
    for length, name in NAMES.items():
        entries = []
        one_images = [(1,) + tail for tail in itertools.product((0, 1), repeat=length - 1)]
        zero_images = list(itertools.product((0, 1), repeat=length))
        for one, zero in itertools.product(one_images, zero_images):
            if sum(one) == sum(zero):
                continue
            columns = column_certificate(one, zero)
            if columns is None:
                continue
            first, rows = analyze(one, zero)
            if first is None:
                continue
            cap = rows[first - 1]["R"]
            language = closed_language(one, zero, first)
            verify_signed_prefixes(one, zero)
            entries.append(render_entry(one, zero, first, cap, language, columns))
        assert len(entries) == COUNTS[length]
        identifier = f"catalogue{name}"
        source = ("import CollatzLab.FiniteContractionEntry\n\n"
                  "/-! Generated by research/phase10/generate_catalogue.py. Every row is\n"
                  "checked independently by the finite Valid predicate in the Lean kernel. -/\n"
                  "set_option maxRecDepth 100000\n"
                  "set_option maxHeartbeats 20000000\n\n"
                  "namespace CollatzLab.Morphism\n\n"
                  f"def {identifier} : List FiniteContractionEntry := [\n"
                  + ",\n".join(entries) + "]\n\n"
                  f"theorem {identifier}_valid : ∀ e ∈ {identifier}, e.Valid := by decide\n\n"
                  f"theorem {identifier}_bounds : ∀ e ∈ {identifier}, e.length = {length} ∧ e.blocks ≤ 8 :=\n"
                  "  by decide\n\n"
                  f"theorem {identifier}_length : {identifier}.length = {len(entries)} := by decide\n\n"
                  "end CollatzLab.Morphism\n")
        modules[ROOT / "CollatzLab" / f"FiniteCatalogue{name}.lean"] = source
    return modules


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    args = parser.parse_args()
    modules = build_modules()
    for path, source in modules.items():
        if args.write:
            path.write_text(source)
        if args.check:
            assert path.read_text() == source, f"generated catalogue differs: {path.name}"
    print("222 finite Lean entries reproduced: lengths 3/4/5/6 with counts 6/10/58/148")
    print("All 222 literal words checked against positive and signed/unreduced 81-step prefixes")
    print("Actual rational exclusion follows only after all finite Valid proofs compile")


if __name__ == "__main__":
    main()
